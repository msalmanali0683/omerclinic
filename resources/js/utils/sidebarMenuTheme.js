export function getMenuTheme(item, parent = null) {
    const colorKey = item.color || parent?.color || 'teal';

    return menuColors[colorKey] || menuColors.teal;
}

export function isMenuPathActive(currentPath, targetPath) {
    if (!targetPath) {
        return false;
    }

    return currentPath === targetPath || currentPath.startsWith(`${targetPath}/`);
}
